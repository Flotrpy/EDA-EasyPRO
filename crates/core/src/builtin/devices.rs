fn model(body: Body, x: f64, y: f64, h: f64, color: u32) -> Option<Model3d> {
    Some(Model3d {
        body,
        size: Point::new(mm(x), mm(y)),
        height: mm(h),
        standoff: 0,
        color,
        offset: Point::ZERO,
    })
}

struct D {
    id: &'static str,
    name: &'static str,
    category: &'static str,
    description: &'static str,
    prefix: &'static str,
    symbol: &'static str,
    footprint: &'static str,
    value: &'static str,
    model: Option<Model3d>,
    attrs: &'static [(&'static str, &'static str)],
    pin_map: &'static [(&'static str, &'static str)],
}

impl From<D> for Device {
    fn from(d: D) -> Device {
        Device {
            id: d.id.into(),
            name: d.name.into(),
            description: d.description.into(),
            category: d.category.into(),
            prefix: d.prefix.into(),
            symbol: d.symbol.into(),
            footprint: (!d.footprint.is_empty()).then(|| d.footprint.into()),
            model: d.model,
            value: d.value.into(),
            attributes: d
                .attrs
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect::<BTreeMap<_, _>>(),
            pin_map: d
                .pin_map
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect(),
        }
    }
}

const CERAMIC: u32 = 0xc8a878;
const BLACK: u32 = 0x1e1e1e;
const RESISTOR: u32 = 0x202020;

fn chip_size(code: &str) -> (f64, f64, f64) {
    match code {
        "0402" => (1.0, 0.5, 0.35),
        "0603" => (1.6, 0.8, 0.45),
        "0805" => (2.0, 1.25, 0.5),
        _ => (3.2, 1.6, 0.55),
    }
}

fn passives() -> Vec<Device> {
    let mut v = Vec::new();
    for code in ["0402", "0603", "0805", "1206"] {
        let (l, w, h) = chip_size(code);
        v.push(Device {
            id: format!("dev:R-{code}"),
            name: format!("Resistor {code}"),
            description: format!("Thick film chip resistor, {code} package"),
            category: "Resistors".into(),
            prefix: "R".into(),
            symbol: "sym:resistor".into(),
            footprint: Some(format!("fp:{code}")),
            model: model(Body::Chip, l, w, h, RESISTOR),
            value: "10k".into(),
            attributes: [("Tolerance".to_string(), "1%".to_string())].into(),
            pin_map: BTreeMap::new(),
        });
        v.push(Device {
            id: format!("dev:C-{code}"),
            name: format!("Capacitor {code}"),
            description: format!("MLCC ceramic capacitor, {code} package"),
            category: "Capacitors".into(),
            prefix: "C".into(),
            symbol: "sym:capacitor".into(),
            footprint: Some(format!("fp:{code}")),
            model: model(Body::Chip, l, w, h + 0.1, CERAMIC),
            value: "100nF".into(),
            attributes: [("Voltage".to_string(), "50V".to_string())].into(),
            pin_map: BTreeMap::new(),
        });
    }
    v
}

fn ic(
    id: &str,
    name: &str,
    left: &[(&str, &str, PinKind)],
    right: &[(&str, &str, PinKind)],
) -> Symbol {
    sym::ic_box(id, name, left, right)
}

