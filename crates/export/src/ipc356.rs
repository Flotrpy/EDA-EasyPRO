//! IPC-D-356A netlist for bare-board electrical test.
//!
//! Fabs use this to test every finished board for opens and shorts against
//! the intended connectivity. Fixed-column records, metric units
//! (`UNITS CUST 1`: 0.001 mm).

use easypro_core::layer::Side;
use easypro_core::library::{Library, PadKind};
use easypro_core::netlist::natural_cmp;
use easypro_core::pcb::Pcb;
use std::collections::BTreeMap;
use std::fmt::Write;

/// Longest net name that fits the net column; longer names get an alias.
const NET_COLS: usize = 14;

/// Coordinate in 0.001 mm with an explicit sign, 6 digits.
fn coord(v: i64) -> String {
    let um = (v as f64 / 1000.0).round() as i64;
    let sign = if um < 0 { '-' } else { '+' };
    format!("{sign}{:06}", um.unsigned_abs().min(999_999))
}

/// Unsigned size in 0.001 mm, 4 digits.
fn size(v: i64) -> String {
    format!("{:04}", ((v as f64 / 1000.0).round() as i64).clamp(0, 9999))
}

struct Record {
    code: &'static str,
    net: String,
    refdes: String,
    pin: String,
    /// (diameter, plated)
    hole: Option<(i64, bool)>,
    /// 0 = both sides, 1 = top, 2 = bottom.
    access: u8,
    x: i64,
    y: i64,
    w: i64,
    h: i64,
    rot: i64,
}

impl Record {
    fn line(&self) -> String {
        let hole = match self.hole {
            Some((d, plated)) => format!("D{}{}", size(d), if plated { 'P' } else { 'U' }),
            None => " ".repeat(6),
        };
        format!(
            "{:3}{:<14}   {:<6}-{:<4} {}A{:02}X{}Y{}X{}Y{}R{:03} S{}",
            self.code,
            self.net,
            self.refdes,
            self.pin,
            hole,
            self.access,
            coord(self.x),
            coord(self.y),
            size(self.w),
            size(self.h),
            self.rot,
            // Soldermask: 0 = open both sides, 1 = top only, 2 = bottom only.
            self.access,
        )
    }
}

/// Write the IPC-D-356A test netlist for `pcb`.
pub fn ipc356(pcb: &Pcb, lib: &Library, job: &str) -> String {
    let mut aliases: BTreeMap<String, String> = BTreeMap::new();
    let mut net_col = |name: &str| -> String {
        if name.is_empty() {
            return "N/C".into();
        }
        if name.len() <= NET_COLS && name.is_ascii() {
            return name.into();
        }
        let n = aliases.len() + 1;
        aliases
            .entry(name.to_string())
            .or_insert_with(|| format!("NNAME{n}"))
            .clone()
    };

    let mut records = Vec::new();
    let mut comps: Vec<_> = pcb.components.iter().collect();
    comps.sort_by(|a, b| natural_cmp(&a.designator, &b.designator));
    for c in comps {
        let Some(fp) = lib.footprints.get(&c.footprint) else {
            continue;
        };
        let tf = c.transform();
        for pad in &fp.pads {
            let at = tf.apply(pad.pos);
            let (code, hole, access) = match pad.kind {
                PadKind::Smd => ("327", None, if c.side == Side::Bottom { 2 } else { 1 }),
                PadKind::Tht { drill } => ("317", Some((drill, true)), 0),
                PadKind::Npth { drill } => ("317", Some((drill, false)), 0),
            };
            let rot = (c.rotation + pad.rotation).rem_euclid(360.0).round() as i64 % 360;
            records.push(Record {
                code,
                net: net_col(c.net_of(&pad.number)),
                refdes: c.designator.chars().take(6).collect(),
                pin: pad.number.chars().take(4).collect(),
                hole,
                access,
                x: at.x,
                y: at.y,
                w: pad.size.x,
                h: pad.size.y,
                rot,
            });
        }
    }
    for v in &pcb.vias {
        records.push(Record {
            code: "317",
            net: net_col(&v.net),
            refdes: "VIA".into(),
            pin: String::new(),
            hole: Some((v.drill, true)),
            access: 0,
            x: v.pos.x,
            y: v.pos.y,
            w: v.diameter,
            h: v.diameter,
            rot: 0,
        });
    }

    let mut out = String::new();
    let _ = writeln!(out, "C  IPC-D-356A netlist generated by EasyPRO");
    let _ = writeln!(out, "P  JOB   {job}");
    let _ = writeln!(out, "P  CODE  00");
    let _ = writeln!(out, "P  UNITS CUST 1");
    let _ = writeln!(out, "P  DIM   N");
    for (full, alias) in &aliases {
        let _ = writeln!(out, "P  {alias:<6}{full}");
    }
    for r in &records {
        let _ = writeln!(out, "{}", r.line().trim_end());
    }
    out.push_str("999\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixed_columns_and_records() {
        let p = easypro_core::examples::regulator();
        let s = ipc356(&p.boards[0].pcb, &p.library, "reg");
        assert!(s.ends_with("999\n"));
        let recs: Vec<&str> = s
            .lines()
            .filter(|l| l.starts_with("317") || l.starts_with("327"))
            .collect();
        let pads: usize = p.boards[0]
            .pcb
            .components
            .iter()
            .map(|c| p.library.footprints[&c.footprint].pads.len())
            .sum();
        assert_eq!(recs.len(), pads + p.boards[0].pcb.vias.len());
        for r in &recs {
            // Access code, X and Y always sit in the same columns.
            assert_eq!(&r[38..39], "A", "{r}");
            assert_eq!(&r[41..42], "X", "{r}");
            assert_eq!(&r[49..50], "Y", "{r}");
        }
        // J1 pin 1 is through-hole on VIN, 5 mm from the left edge.
        let j1 = recs
            .iter()
            .find(|r| r[20..].starts_with("J1    -1 "))
            .unwrap();
        assert_eq!(j1[3..17].trim(), "VIN");
        assert!(j1.contains("A00X+005000Y+012270"), "{j1}");
        assert!(j1[32..38].starts_with('D') && j1[32..38].ends_with('P'));
        // SMD pads are top-side test points.
        assert!(recs
            .iter()
            .any(|r| r.starts_with("327+3V3") && r.contains("A01")));
    }

    #[test]
    fn long_net_names_are_aliased() {
        let mut p = easypro_core::examples::regulator();
        for c in &mut p.boards[0].pcb.components {
            for n in c.pad_nets.values_mut() {
                if n == "LED_A" {
                    *n = "POWER_INDICATOR_ANODE".into();
                }
            }
        }
        let s = ipc356(&p.boards[0].pcb, &p.library, "reg");
        assert!(s.contains("P  NNAME1POWER_INDICATOR_ANODE"));
        assert!(s.lines().any(|l| l.starts_with("327NNAME1")));
    }
}
