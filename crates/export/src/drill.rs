//! Excellon drill files (metric, decimal coordinates).

use easypro_core::geom::Point;
use easypro_core::library::{Library, PadKind};
use easypro_core::pcb::Pcb;
use std::collections::BTreeMap;
use std::fmt::Write;

#[derive(Clone, Debug, Default, PartialEq)]
pub struct DrillTable {
    /// Diameter (nm) -> hit positions.
    pub tools: BTreeMap<i64, Vec<Point>>,
}

impl DrillTable {
    pub fn hits(&self) -> usize {
        self.tools.values().map(|v| v.len()).sum()
    }
}

/// Collect holes. `plated` selects PTH (vias + plated pads) or NPTH.
pub fn holes(pcb: &Pcb, lib: &Library, plated: bool) -> DrillTable {
    let mut t = DrillTable::default();
    if plated {
        for v in &pcb.vias {
            t.tools.entry(v.drill).or_default().push(v.pos);
        }
    }
    for (c, pad, _) in pcb.pads(lib) {
        let d = match (pad.kind, plated) {
            (PadKind::Tht { drill }, true) | (PadKind::Npth { drill }, false) => drill,
            _ => continue,
        };
        t.tools
            .entry(d)
            .or_default()
            .push(c.transform().apply(pad.pos));
    }
    for v in t.tools.values_mut() {
        v.sort();
    }
    t
}

fn mm3(nm: i64) -> String {
    format!("{:.3}", nm as f64 / 1e6)
}

pub fn excellon(table: &DrillTable, plated: bool) -> String {
    let mut out = String::new();
    out.push_str("M48\n");
    let _ = writeln!(
        out,
        "; DRILL file generated by EasyPRO, {} holes",
        if plated { "plated" } else { "non-plated" }
    );
    let _ = writeln!(
        out,
        "; #@! TF.FileFunction,{},1,2,{}",
        if plated { "Plated" } else { "NonPlated" },
        if plated { "PTH" } else { "NPTH" }
    );
    out.push_str("FMAT,2\nMETRIC,TZ\n");
    for (i, d) in table.tools.keys().enumerate() {
        let _ = writeln!(out, "T{}C{}", i + 1, mm3(*d));
    }
    out.push_str("%\nG90\nG05\n");
    for (i, pts) in table.tools.values().enumerate() {
        let _ = writeln!(out, "T{}", i + 1);
        for p in pts {
            let _ = writeln!(out, "X{}Y{}", mm3(p.x), mm3(p.y));
        }
    }
    out.push_str("T0\nM30\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use easypro_core::examples::blinker;

    #[test]
    fn header_has_two_holes() {
        let p = blinker();
        let t = holes(&p.boards[0].pcb, &p.library, true);
        assert_eq!(t.hits(), 2, "J1 is the only through-hole part");
        let text = excellon(&t, true);
        assert!(text.starts_with("M48"));
        assert!(text.contains("T1C1.000"));
        assert!(text.trim_end().ends_with("M30"));
        assert_eq!(holes(&p.boards[0].pcb, &p.library, false).hits(), 0);
    }
}
